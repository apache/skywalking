    private TalExpression compile(final String dsl) throws Exception {
        final TALClassGenerator generator = new TALClassGenerator();
        generator.setClassNameHint("exec_" + Math.abs(dsl.hashCode()));
        // A prefix of this test's own: MeterSystem's generated metric classes live in a process-wide ClassPool
        // while meterPrototypes is per instance, so a name another test class already created would be found in
        // the pool and missing from this test's registry.
        generator.setMetricPrefix("tal_exec_test");
        generator.setInputType(TestSpanInput.class);
        generator.setSourceRef(DslSourceRef.ofRule("tal/test.yaml", 1));
        generator.setClassOutputDir(DslClassOutput.unitTestDir("tal"));

        final TalExpression expression = generator.compile(dsl);
        generator.createMetrics(meterSystem);
        return expression;
    }

    private ExecutionContext execute(final TalExpression expression, final SpanMetadata meta,
                                     final TestSpanInput input) {
        final ExecutionContext ctx = new ExecutionContext();
        ctx.setSourceTypeProvider(new TestSpanSourceTypeProvider());
        ctx.init(meta, input, Collections.emptyMap(), Collections.emptyMap());
        expression.execute(filterSpec, ctx);
        return ctx;
    }

