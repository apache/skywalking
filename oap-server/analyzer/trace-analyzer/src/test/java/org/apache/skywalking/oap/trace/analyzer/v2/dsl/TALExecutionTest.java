    @Test
    void aRootServerSpanDrawsTheUserEdgeWithoutListingUser() throws Exception {
        final TalExpression rule = compile("filter { extractor {\n"
            + "  layer \"OTLP_SERVICE\"\n"
            + "  if (meta.root) {\n"
            + "    def fromUser = serviceRelation(SERVER, \"User\", \"UNDEFINED\", meta.service, meta.layer,"
            + "                   component(\"http\"))\n"
            + "    metrics { name \"user_rel_server_cpm\"; scope fromUser; function cpm; value 1 }\n"
            + "  }\n"
            + "} }");
        execute(rule, serverSpan(), new TestSpanInput());

        assertEquals(1, sentValues.size());
        // The agent path builds User's id from Layer.UNDEFINED's own flag, non-normal, and ServiceTopologyBuilder
        // recognizes the node by that id; a two-layer relation has to produce the same one.
        final String user = IDManager.ServiceID.buildId("User", false);
        assertEquals(
            IDManager.ServiceID.buildRelationId(new IDManager.ServiceID.ServiceRelationDefine(
                user, IDManager.ServiceID.buildId("frontend", true))),
            entityIdOf(sentValues.get(0)));
        assertEquals(1, traffic.stream().filter(ServiceRelationServerSideMetrics.class::isInstance)
            .map(ServiceRelationServerSideMetrics.class::cast)
            .filter(r -> user.equals(r.getSourceServiceId()))
            .count(), "the server-side relation row names User as its source: " + traffic);
        assertEquals(List.of("frontend"), traffic.stream().filter(ServiceTraffic.class::isInstance)
            .map(r -> ((ServiceTraffic) r).getName()).collect(Collectors.toList()),
            "User is a node of the topology, not a service in any list");

        // A span with a parent was called by a service of the fleet, which its caller's CLIENT span reports.
        sentValues.clear();
        execute(rule, SpanMetadata.builder().service("frontend").endpoint("HTTP GET")
                                  .kind(SpanMetadata.KIND_SERVER).statusCode(SpanMetadata.STATUS_UNSET)
                                  .startTime(SPAN_START_MILLIS).timestamp(SPAN_END_MILLIS).latency(110)
                                  .traceId("aabb").spanId("eeff").parentSpanId("ccdd").build(),
            new TestSpanInput());
        assertTrue(sentValues.isEmpty(), "no User edge for a span with a parent: " + sentValues);
    }

