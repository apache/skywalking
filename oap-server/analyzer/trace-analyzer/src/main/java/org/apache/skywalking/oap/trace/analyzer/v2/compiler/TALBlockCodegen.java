    /**
     * A {@code persist} block. An empty one is still a vote: it says keep.
     */
    private static void generatePersistBlock(final StringBuilder sb,
                                             final List<TALScriptModel.VoteStatement> stmts,
                                             final TALGenCtx genCtx) {
        if (genCtx.extractorDepth > 0 || genCtx.voteDepth > 0) {
            throw new IllegalArgumentException(
                "persist {} belongs at the filter level, not inside an extractor or a persist block");
        }
        genCtx.voteDepth++;
        sb.append("  {\n");
        // A block that runs votes keep for the span unless a statement in it says otherwise.
        sb.append("    ctx.votePersist(true);\n");
        final List<TALScriptModel.FilterStatement> asFilter = new ArrayList<>(stmts.size());
        for (final TALScriptModel.VoteStatement vs : stmts) {
            asFilter.add((TALScriptModel.FilterStatement) vs);
        }
        generateStatements(sb, asFilter, genCtx);
        sb.append("  }\n");
        genCtx.voteDepth--;
    }

    // ==================== Extractor ====================

    /**
     * The extractor's statements, inline. The block cannot be nested in another extractor, and only reaches the
     * persist block through {@link #generatePersistBlock}, which refuses it.
     */
    private static void generateExtractorBlock(final StringBuilder sb,
                                               final TALScriptModel.ExtractorBlock block,
                                               final TALGenCtx genCtx) {
        if (genCtx.extractorDepth > 0 || genCtx.voteDepth > 0) {
            throw new IllegalArgumentException(
                "extractor {} belongs at the filter level, not inside an extractor or a persist block");
        }
        final List<TALScriptModel.FilterStatement> stmts = new ArrayList<>();
        for (final TALScriptModel.ExtractorStatement es : block.getStatements()) {
            stmts.add((TALScriptModel.FilterStatement) es);
        }
        genCtx.extractorDepth++;
        sb.append("  {\n");
        generateStatements(sb, stmts, genCtx);
        sb.append("  }\n");
        genCtx.extractorDepth--;
    }

    /**
     * Dispatch a list of statements.
     */
    static void generateStatements(final StringBuilder sb,
                                   final List<? extends TALScriptModel.FilterStatement> stmts,
                                   final TALGenCtx genCtx) {
        for (int i = 0; i < stmts.size(); i++) {
            final TALScriptModel.FilterStatement stmt = stmts.get(i);
            try {
                // abort {} returns, so a statement after it in the same block could never run; Java refuses that
                // code too, and Javassist would emit bytecode the verifier rejects.
                if (stmt instanceof TALScriptModel.AbortStatement && i < stmts.size() - 1) {
                    throw new IllegalArgumentException(
                        "abort {} ends its block; the statements after it in the same block never run");
                }
                generateStatement(sb, stmt, genCtx);
            } catch (final RuntimeException e) {
                if (!genCtx.discoveringTypes) {
                    throw e;
                }
                discoverInside(stmt, genCtx);
            }
        }
    }

    /**
     * In a discovery generation, a block whose own part failed, such as its condition or its list, still has the
     * statements inside it generated, into a buffer nobody reads, so a {@code segmentDef} declared there is typed.
     */
    private static void discoverInside(final TALScriptModel.FilterStatement stmt,
                                       final TALGenCtx genCtx) {
        final StringBuilder discarded = new StringBuilder();
        final List<List<?>> inside = new ArrayList<>();
        if (stmt instanceof TALScriptModel.IfBlock) {
            inside.add(((TALScriptModel.IfBlock) stmt).getThenStatements());
            inside.add(((TALScriptModel.IfBlock) stmt).getElseStatements());
        } else if (stmt instanceof TALScriptModel.ForeachBlock) {
            inside.add(((TALScriptModel.ForeachBlock) stmt).getBody());
        } else if (stmt instanceof TALScriptModel.ExtractorBlock) {
            inside.add(((TALScriptModel.ExtractorBlock) stmt).getStatements());
        } else if (stmt instanceof TALScriptModel.BuildBlock) {
            inside.add(((TALScriptModel.BuildBlock) stmt).getStatements());
        } else if (stmt instanceof TALScriptModel.FirstBlock) {
            inside.add(((TALScriptModel.FirstBlock) stmt).getStatements());
        } else if (stmt instanceof TALScriptModel.PersistBlock) {
            inside.add(((TALScriptModel.PersistBlock) stmt).getStatements());
        }
        for (final List<?> statements : inside) {
            final List<TALScriptModel.FilterStatement> asFilter = new ArrayList<>(statements.size());
            for (final Object inner : statements) {
                if (inner instanceof TALScriptModel.FilterStatement) {
                    asFilter.add((TALScriptModel.FilterStatement) inner);
                }
            }
            generateStatements(discarded, asFilter, genCtx);
        }
    }

    private static void generateStatement(final StringBuilder sb,
                                          final TALScriptModel.FilterStatement stmt,
                                          final TALGenCtx genCtx) {
        if (stmt instanceof TALScriptModel.AbortStatement) {
            // A guarded return: an unconditional one at the end of a block makes the statements after the block
            // unreachable, and the bytecode Javassist emits for them fails verification.
            sb.append("  h.ctx().abort();\n");
            sb.append("  if (h.ctx().isAborted()) {\n");
            sb.append("    return;\n");
            sb.append("  }\n");
        } else if (stmt instanceof TALScriptModel.ExtractorBlock) {
            generateExtractorBlock(sb, (TALScriptModel.ExtractorBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.PersistBlock) {
            TALInputs.require(TALConstruct.PERSIST, genCtx.inputAlias);
            generatePersistBlock(sb, ((TALScriptModel.PersistBlock) stmt).getStatements(), genCtx);
        } else if (stmt instanceof TALScriptModel.DefStatement) {
            TALDefCodegen.generateDefStatement(sb, (TALScriptModel.DefStatement) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.AssignStatement) {
            TALDefCodegen.generateAssignStatement(sb, (TALScriptModel.AssignStatement) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.ForeachBlock) {
            generateForeachBlock(sb, (TALScriptModel.ForeachBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.LogStatement) {
            generateLogStatement(sb, (TALScriptModel.LogStatement) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.FieldAssignment) {
            generateFieldAssignment(sb, (TALScriptModel.FieldAssignment) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.TagAssignment) {
            generateTagAssignment(sb, (TALScriptModel.TagAssignment) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.NetworkAliasStatement) {
            generateNetworkAliasStatement(sb, (TALScriptModel.NetworkAliasStatement) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.MetricsBlock) {
            generateMetricsBlock(sb, (TALScriptModel.MetricsBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.EnforcerStatement) {
            requireVoteBlock("enforcer {}", genCtx);
            sb.append("  filterSpec.enforcer(h.ctx());\n");
        } else if (stmt instanceof TALScriptModel.DropperStatement) {
            requireVoteBlock("dropper {}", genCtx);
            sb.append("  filterSpec.dropper(h.ctx());\n");
        } else if (stmt instanceof TALScriptModel.SamplerBlock) {
            requireVoteBlock("sampler {}", genCtx);
            generateSamplerBlock(sb, (TALScriptModel.SamplerBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.IfBlock) {
            generateIfBlock(sb, (TALScriptModel.IfBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.SegmentDefStatement) {
            TALDefCodegen.generateSegmentDefStatement(sb, (TALScriptModel.SegmentDefStatement) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.BuildBlock) {
            generateBuildBlock(sb, (TALScriptModel.BuildBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.SourceBlock) {
            generateSourceBlock(sb, (TALScriptModel.SourceBlock) stmt, genCtx);
        } else if (stmt instanceof TALScriptModel.WriteNetworkAliasStatement) {
            final TALScriptModel.WriteNetworkAliasStatement alias = (TALScriptModel.WriteNetworkAliasStatement) stmt;
            TALInputs.require(TALConstruct.WRITE_NETWORK_ALIAS, genCtx.inputAlias);
            sb.append("  ").append(TALRuntimeRoles.method("writeNetworkAlias")).append("(h, ");
            TALValueCodegen.generateStringValueAccess(sb, alias.getValue(), alias.getCastType(), genCtx);
            sb.append(");\n");
        } else if (stmt instanceof TALScriptModel.FirstBlock) {
            // TALClassGenerator takes the ones written directly in filter {} into their own method.
            TALInputs.require(TALConstruct.FIRST, genCtx.inputAlias);
            throw new IllegalArgumentException(
                "first {} belongs directly in filter {}, not inside another block: it is a run of its own, on every "
                    + "span whose spanId is 0");
        } else {
            throw new IllegalArgumentException(
                "Unsupported TAL statement in codegen: " + stmt.getClass().getSimpleName());
        }
    }

    /**
     * The vote statements decide the span's fate, so they mean something only inside {@code persist {}}.
     */
    private static void requireVoteBlock(final String statement, final TALGenCtx genCtx) {
        if (genCtx.voteDepth == 0) {
            throw new IllegalArgumentException(statement + " belongs inside a persist {} block");
        }
    }

    /**
     * {@code foreach (x in list) { ... }}: an iterator over the list, the loop variable typed to the list's element
     * type when the rule compiles. A def first declared in the body belongs to one iteration: it is reset when an
     * iteration starts, so a branch an iteration does not take reads null, and it is out of scope after the body.
     */
    private static void generateForeachBlock(final StringBuilder sb,
                                             final TALScriptModel.ForeachBlock block,
                                             final TALGenCtx genCtx) {
        final String varName = block.getVarName();
        if (genCtx.localVars.containsKey(varName)) {
            throw new IllegalArgumentException(
                "foreach (" + varName + " in ...) names a variable already declared; choose another name");
        }
        final StringBuilder listExpr = new StringBuilder();
        TALValueCodegen.generateValueAccess(listExpr, block.getList(), genCtx);
        final Class<?> listType = genCtx.lastResolvedType;
        final Class<?> elementType = genCtx.lastResolvedElementType;
        if (listType == null || !List.class.isAssignableFrom(listType)) {
            throw new IllegalArgumentException(
                "foreach (" + varName + " in " + block.getList().toPathString() + ") walks a java.util.List, not "
                    + (listType == null ? "a value of unknown type" : "a " + listType.getSimpleName()));
        }
        if (elementType == null) {
            throw new IllegalArgumentException(
                "foreach (" + varName + " in " + block.getList().toPathString() + "): the list's element type is "
                    + "not known when the rule compiles; the getter or function must return a generic List<T>");
        }
        final String iterator = genCtx.nextLocalName("_it");
        genCtx.localVarDecls.append("  java.util.Iterator ").append(iterator).append(" = null;\n");
        genCtx.localVarLvtVars.add(new String[] {iterator, "Ljava/util/Iterator;"});
        final String loopVar = genCtx.nextLocalName("_each_" + varName + "_");
        genCtx.localVarDecls.append("  ").append(TALCodegenHelper.javaTypeName(elementType)).append(" ").append(loopVar)
                           .append(" = null;\n");
        genCtx.localVarLvtVars.add(new String[] {loopVar, TALCodegenHelper.descriptor(elementType)});
        genCtx.localVars.put(varName, new TALLocalVar(loopVar, elementType));

        genCtx.blockScopes.addLast(new ArrayList<>());
        final StringBuilder body = new StringBuilder();
        generateStatements(body, block.getBody(), genCtx);
        final List<String> declaredInBody = genCtx.blockScopes.removeLast();

        sb.append("  ").append(iterator).append(" = ").append(TALRuntimeRoles.method("iterate")).append("(").append(listExpr).append(");\n");
        sb.append("  while (").append(iterator).append(".hasNext()) {\n");
        sb.append("  ").append(loopVar).append(" = (").append(TALCodegenHelper.javaTypeName(elementType)).append(") ")
          .append(iterator).append(".next();\n");
        for (final String name : declaredInBody) {
            sb.append("  ").append(genCtx.localVars.get(name).javaVarName).append(" = null;\n");
        }
        sb.append(body);
        sb.append("  }\n");

        genCtx.localVars.remove(varName);
        for (final String name : declaredInBody) {
            genCtx.localVars.remove(name);
            genCtx.entityScopeTypes.remove(name);
        }
    }

    /**
     * {@code log <level> "<message>", args}: under the script's logger, the arguments evaluated only when the level
     * is enabled, as the Java's {@code isDebugEnabled()} guards do.
     */
    private static void generateLogStatement(final StringBuilder sb,
                                             final TALScriptModel.LogStatement stmt,
                                             final TALGenCtx genCtx) {
        final String level = stmt.getLevel();
        final String enabled = "is" + Character.toUpperCase(level.charAt(0)) + level.substring(1) + "Enabled";
        sb.append("  if (").append(TALClassGenerator.SCRIPT_LOGGER).append(".").append(enabled).append("()) {\n");
        sb.append("    ").append(TALClassGenerator.SCRIPT_LOGGER).append(".").append(level).append("(\"")
          .append(DslJavaSourceText.toLiteral(stmt.getMessage())).append("\", ");
        if (stmt.getArguments().isEmpty()) {
            // Javassist's compiler takes no empty array initializer.
            sb.append("new Object[0]);\n");
        } else {
            sb.append("new Object[] {");
            for (int i = 0; i < stmt.getArguments().size(); i++) {
                if (i > 0) {
                    sb.append(", ");
                }
                final TALScriptModel.FunctionArg arg = stmt.getArguments().get(i);
                TALValueCodegen.generateBoxedValueAccess(sb, arg.getValue(), arg.getCastType(), genCtx);
            }
            sb.append("});\n");
        }
        sb.append("  }\n");
    }

    private static void generateIfBlock(final StringBuilder sb,
                                        final TALScriptModel.IfBlock block,
                                        final TALGenCtx genCtx) {
        sb.append("  if (");
        TALValueCodegen.generateCondition(sb, block.getCondition(), genCtx);
        sb.append(") {\n");
        generateStatements(sb, block.getThenStatements(), genCtx);
        sb.append("  }\n");
        if (!block.getElseStatements().isEmpty()) {
            sb.append("  else {\n");
            generateStatements(sb, block.getElseStatements(), genCtx);
            sb.append("  }\n");
        }
    }

    /**
     * {@code service}, {@code instance}, {@code endpoint} and {@code layer} overwrite the metadata view.
     */
    private static void generateFieldAssignment(final StringBuilder sb,
                                                final TALScriptModel.FieldAssignment stmt,
                                                final TALGenCtx genCtx) {
        final String setter;
        final TALConstruct construct;
        switch (stmt.getFieldType()) {
            case SERVICE:
                setter = "setService";
                construct = TALConstruct.SERVICE;
                break;
            case INSTANCE:
                setter = "setServiceInstance";
                construct = TALConstruct.INSTANCE;
                break;
            case ENDPOINT:
                setter = "setEndpoint";
                construct = TALConstruct.ENDPOINT;
                break;
            case LAYER:
            default:
                setter = "setLayer";
                construct = TALConstruct.LAYER;
                break;
        }
        TALInputs.require(construct, genCtx.inputAlias);
        sb.append("  h.ctx().getMeta().").append(setter).append("(");
        TALValueCodegen.generateStringValueAccess(sb, stmt.getValue(), stmt.getCastType(), genCtx);
        sb.append(");\n");
    }

    /**
     * @param owner what the type is to the rule, for the error, such as {@code source <Name> {}}
     * @return the setter for a field, or a compile error naming what the type does offer
     */
    private static Method findSetter(final Class<?> type, final String field, final String owner) {
        final String wanted = "set" + Character.toUpperCase(field.charAt(0)) + field.substring(1);
        for (final Method m : type.getMethods()) {
            if (m.getName().equals(wanted) && m.getParameterCount() == 1) {
                return m;
            }
        }
        final Set<String> available = new TreeSet<>();
        for (final Method m : type.getMethods()) {
            if (m.getName().startsWith("set") && m.getName().length() > 3 && m.getParameterCount() == 1) {
                available.add(Character.toLowerCase(m.getName().charAt(3)) + m.getName().substring(4));
            }
        }
        throw new IllegalArgumentException(owner + " has no field '" + field + "'; it offers " + available);
    }

    /**
     * {@code build {}}: queues the block with the values of the {@code def} variables in scope, which its own method,
     * generated after this one, reads back; see {@code TALClassGenerator}. The run sends nothing here.
     */
    private static void generateBuildBlock(final StringBuilder sb,
                                           final TALScriptModel.BuildBlock block,
                                           final TALGenCtx genCtx) {
        TALInputs.require(TALConstruct.BUILD, genCtx.inputAlias);
        if (genCtx.extractorDepth == 0) {
            throw new IllegalArgumentException("build {} belongs inside extractor {}");
        }
        if (genCtx.buildDepth > 0) {
            throw new IllegalArgumentException(
                "build {} cannot sit inside another build {}: a queued block runs once, after the segment's last span");
        }
        final Map<String, TALLocalVar> captured = new LinkedHashMap<>();
        final Map<String, String> scopes = new HashMap<>();
        new TreeMap<>(genCtx.localVars).forEach((name, var) -> {
            if (var.segmentSlot < 0) {
                captured.put(name, var);
                if (genCtx.entityScopeTypes.containsKey(name)) {
                    scopes.put(name, genCtx.entityScopeTypes.get(name));
                }
            }
        });
        final int index = genCtx.builds.size();
        genCtx.builds.add(new TALGenCtx.BuildSite(block, captured, scopes));
        sb.append("  h.ctx().queueBuild(").append(index).append(", ");
        if (captured.isEmpty()) {
            // Javassist's compiler takes no empty array initializer.
            sb.append("new Object[0]");
        } else {
            sb.append("new Object[] {");
            boolean first = true;
            for (final TALLocalVar var : captured.values()) {
                sb.append(first ? "" : ", ").append(var.javaVarName);
                first = false;
            }
            sb.append("}");
        }
        sb.append(");\n");
    }

    /**
     * {@code source <Name> {}}: one source, its fields set in order, sent to the source receiver at the statement,
     * which dispatches it by its scope, to OAL or to the dispatcher a module declares. On an input with
     * {@code build {}} the block sits inside one, so it is sent in the segment's build phase.
     */
    private static void generateSourceBlock(final StringBuilder sb,
                                            final TALScriptModel.SourceBlock block,
                                            final TALGenCtx genCtx) {
        final String what = "source " + block.getName() + " {}";
        if (TALInputs.has(TALConstruct.BUILD, genCtx.inputAlias)) {
            requireBuild(what, genCtx);
        }
        final Class<?> type = sourceClass(block.getName());
        if (block.getFields().stream().noneMatch(field -> "timeBucket".equals(field.getField()))) {
            throw new IllegalArgumentException(
                what + " sets no timeBucket: minuteTimeBucket(...) for a metrics source, recordTimeBucket(...) for a "
                    + "record source");
        }
        final String typeName = type.getName();
        final String var = genCtx.nextLocalName("_src");
        genCtx.localVarDecls.append("  ").append(typeName).append(" ").append(var).append(" = null;\n");
        genCtx.localVarLvtVars.add(new String[] {var, TALCodegenHelper.descriptor(type)});
        sb.append("  ").append(var).append(" = new ").append(typeName).append("();\n");
        for (final TALScriptModel.SourceField field : block.getFields()) {
            final Method setter = outputSetter(type, field, what, genCtx);
            sb.append("  ").append(var).append(".").append(setter.getName()).append("(");
            TALValueCodegen.generateArgumentFor(sb, field.getValue(), field.getCastType(),
                setter.getParameterTypes()[0], what + " field '" + field.getField() + "'", genCtx);
            sb.append(");\n");
        }
        sb.append("  filterSpec.getSourceReceiver().receive(").append(var).append(");\n");
    }

    /**
     * The setter of a {@code source} field; among overloads, the one the value's type fits best, as a function call
     * chooses, and a compile error when none or several fit equally.
     */
    private static Method outputSetter(final Class<?> type, final TALScriptModel.SourceField field, final String what,
                                       final TALGenCtx genCtx) {
        final String wanted = "set" + Character.toUpperCase(field.getField().charAt(0)) + field.getField().substring(1);
        final List<Method> overloads = new ArrayList<>();
        for (final Method m : type.getMethods()) {
            if (m.getName().equals(wanted) && m.getParameterCount() == 1) {
                overloads.add(m);
            }
        }
        if (overloads.size() <= 1) {
            return overloads.isEmpty() ? findSetter(type, field.getField(), what) : overloads.get(0);
        }
        final Class<?>[] valueType = TALValueCodegen.argumentTypes(
            List.of(new TALScriptModel.FunctionArg(field.getValue(), field.getCastType())), genCtx);
        final Method best = TALFunctionRegistry.bestMethod(overloads, valueType);
        if (best == null) {
            final Set<String> params = new TreeSet<>();
            overloads.forEach(m -> params.add(m.getParameterTypes()[0].getSimpleName()));
            throw new IllegalArgumentException(
                what + " field '" + field.getField() + "' has setters taking " + params + ", and its value of type "
                    + (valueType[0] == null ? "unknown" : valueType[0].getSimpleName())
                    + " fits none, or several equally; convert it with as <Type>");
        }
        return best;
    }

    /**
     * @return the class declaring the OAL scope of that name, when it is a source the rule can create
     */
    private static Class<?> sourceClass(final String name) {
        final Class<?> type = DefaultScopeDefine.classOf(name);
        if (type == null || !isCreatableSource(type)) {
            final Set<String> known = new TreeSet<>();
            for (final String declared : DefaultScopeDefine.names()) {
                if (isCreatableSource(DefaultScopeDefine.classOf(declared))) {
                    known.add(declared);
                }
            }
            throw new IllegalArgumentException(
                "source " + name + " {} names no declared source; the known sources are " + known);
        }
        return type;
    }

    private static boolean isCreatableSource(final Class<?> type) {
        if (!ISource.class.isAssignableFrom(type) || Modifier.isAbstract(type.getModifiers())
            || !Modifier.isPublic(type.getModifiers())) {
            return false;
        }
        try {
            type.getConstructor();
            return true;
        } catch (final NoSuchMethodException e) {
            return false;
        }
    }

    /**
     * An input whose rules build, as the native input does, writes its outputs inside {@code build {}} only.
     */
    private static void requireBuild(final String what, final TALGenCtx genCtx) {
        if (genCtx.buildDepth == 0) {
            throw new IllegalArgumentException(
                what + " belongs inside build {}: a rule of inputType " + genCtx.inputAlias
                    + " writes its outputs there");
        }
    }

    private static void generateTagAssignment(final StringBuilder sb,
                                              final TALScriptModel.TagAssignment stmt,
                                              final TALGenCtx genCtx) {
        TALInputs.require(TALConstruct.TAG, genCtx.inputAlias);
        for (final Map.Entry<String, TALScriptModel.TagValue> e : stmt.getTags().entrySet()) {
            sb.append("  h.ctx().addTag(\"").append(DslJavaSourceText.toLiteral(e.getKey())).append("\", ");
            TALValueCodegen.generateStringValueAccess(
                sb, e.getValue().getValue(), e.getValue().getCastType(), genCtx);
            sb.append(");\n");
        }
    }

    private static void generateNetworkAliasStatement(final StringBuilder sb,
                                                      final TALScriptModel.NetworkAliasStatement stmt,
                                                      final TALGenCtx genCtx) {
        TALInputs.require(
            stmt.isBuild() ? TALConstruct.BUILD_NETWORK_ALIAS : TALConstruct.PREPARE_NETWORK_ALIAS, genCtx.inputAlias);
        if (!stmt.isBuild()) {
            // Recorded only: TraceAnalyzerServiceImpl sends the caller half once the rules have run, so a rule that
            // aborts later sends none.
            sb.append("  h.ctx().prepareNetworkAlias(");
            TALValueCodegen.generateStringValueAccess(sb, stmt.getValue(), stmt.getCastType(), genCtx);
            sb.append(");\n");
            return;
        }
        // The address is composed on the trace's owner from the matched caller half, by the method
        // TALClassGenerator generates from this statement; here the span is only marked as the callee half.
        if (genCtx.networkAliasBuild != null && genCtx.networkAliasBuild != stmt) {
            throw new IllegalArgumentException(
                "a rule declares buildNetworkAlias once: the trace's owner composes one alias address per call, "
                    + "from the rule the callee half names");
        }
        genCtx.networkAliasBuild = stmt;
        sb.append("  h.ctx().requestNetworkAlias();\n");
    }

    private static void generateSamplerBlock(final StringBuilder sb,
                                             final TALScriptModel.SamplerBlock block,
                                             final TALGenCtx genCtx) {
        for (final TALScriptModel.SamplerContent content : block.getContents()) {
            if (content instanceof TALScriptModel.RateLimitBlock) {
                final TALScriptModel.RateLimitBlock rl = (TALScriptModel.RateLimitBlock) content;
                sb.append("  filterSpec.rateLimit(h.ctx(), ");
                appendRateLimitId(sb, rl, genCtx);
                sb.append(", ").append(rl.getRpm()).append(");\n");
            } else if (content instanceof TALScriptModel.IfBlock) {
                generateIfBlock(sb, (TALScriptModel.IfBlock) content, genCtx);
            } else if (content instanceof TALScriptModel.ForeachBlock) {
                generateForeachBlock(sb, (TALScriptModel.ForeachBlock) content, genCtx);
            } else if (content instanceof TALScriptModel.LogStatement) {
                generateLogStatement(sb, (TALScriptModel.LogStatement) content, genCtx);
            }
        }
    }

    /**
     * A {@code ${...}} placeholder makes the id per-span, so the counter is built at runtime; a plain id is a
     * constant.
     */
    private static void appendRateLimitId(final StringBuilder sb,
                                          final TALScriptModel.RateLimitBlock rl,
                                          final TALGenCtx genCtx) {
        if (!rl.isIdInterpolated()) {
            sb.append("\"").append(DslJavaSourceText.toLiteral(rl.getId())).append("\"");
            return;
        }
        sb.append("(\"\"");
        for (final TALScriptModel.InterpolationPart part : rl.getIdParts()) {
            sb.append(" + ");
            if (part.isLiteral()) {
                sb.append("\"").append(DslJavaSourceText.toLiteral(part.getText())).append("\"");
            } else {
                TALValueCodegen.generateStringValueAccess(sb, part.getExpression(), part.getCastType(), genCtx);
            }
        }
        sb.append(")");
    }

    // ==================== Metrics ====================

    /**
     * One {@code metrics {}} block becomes this sequence: build the entity, read the observation and the time,
     * build the metric, register the entity's traffic once, accept the observation and send it in that minute
     * bucket. Everything that can fail runs before any traffic, and a failure anywhere in the block skips only the
     * block: a value that does not parse costs that metric for that span, not the rule's later blocks.
     */
    private static void generateMetricsBlock(final StringBuilder sb,
                                             final TALScriptModel.MetricsBlock block,
                                             final TALGenCtx genCtx) {
        if (TALInputs.has(TALConstruct.BUILD, genCtx.inputAlias)) {
            requireBuild("metrics {}", genCtx);
        }
        final TALMetricFunction function = TALMetricFunction.of(block.getFunction());
        final String fullName = genCtx.metricPrefix == null || genCtx.metricPrefix.isEmpty()
            ? block.getName() : genCtx.metricPrefix + "_" + block.getName();
        validate(block, function, fullName);
        final List<Long> bounds = bucketBounds(block, fullName);
        final List<Integer> ranks = ranks(block, function, fullName);
        final int labelLimit = labelLimit(block, function, fullName);

        final String entityVar = genCtx.nextLocalName("_e");
        final String valueVar = genCtx.nextLocalName("_v");
        final String observationVar = genCtx.nextLocalName("_o");
        final String timeVar = genCtx.nextLocalName("_t");
        final String failureVar = genCtx.nextLocalName("_x");

        sb.append("  try {\n");
        sb.append("    ").append(METER_ENTITY).append(" ").append(entityVar).append(" = ");
        final String scopeType = appendEntity(sb, block.getScope(), genCtx);
        sb.append(";\n");
        if (function.kind == TALMetricFunction.Kind.APDEX && scopeType.endsWith("_RELATION")) {
            throw new IllegalArgumentException(
                "apdex needs a service, instance or endpoint scope, whose service names the threshold; metric "
                    + fullName + " is scoped to a relation");
        }
        // A layer name that is not registered resolves to null, see TalMetricsRuntime.layer, and the block is skipped
        // rather than filed under a layer the rule did not name.
        sb.append("    if (").append(TALRuntimeRoles.method("layerResolved")).append("(").append(entityVar).append(")) {\n");
        sb.append("      Object ").append(observationVar).append(" = ");
        appendObservation(sb, block, function, entityVar, bounds, ranks, genCtx);
        sb.append(";\n");
        sb.append("      long ").append(timeVar).append(" = ");
        if (block.getTimestamp() != null) {
            appendLong(sb, block.getTimestamp(), block.getTimestampCast(), genCtx);
        } else {
            // The span's start, the minute the agent path buckets a call in.
            sb.append("h.ctx().getMeta().getStartTime()");
        }
        sb.append(";\n");
        // The metric is built before the entity is registered, so a metric that cannot be built leaves no traffic.
        sb.append("      ").append(ACCEPTABLE_VALUE).append(" ").append(valueVar)
          .append(" = h.spec().getMeterSystem().buildMetrics(\"")
          .append(DslJavaSourceText.toLiteral(fullName)).append("\", ")
          .append(function.valueClass).append(".class);\n");
        sb.append("      ").append(TALRuntimeRoles.method("traffic")).append("(h, ").append(entityVar).append(", ").append(timeVar).append(");\n");
        sb.append("      ").append(valueVar).append(".accept(").append(entityVar).append(", ")
          .append(observationVar).append(");\n");
        sb.append("      ").append(TALRuntimeRoles.method("send")).append("(h, ").append(valueVar).append(", ").append(timeVar).append(");\n");
        sb.append("    }\n");
        sb.append("  } catch (RuntimeException ").append(failureVar).append(") {\n");
        sb.append("    ").append(TALRuntimeRoles.method("metricsBlockFailed")).append("(\"").append(DslJavaSourceText.toLiteral(fullName)).append("\", ")
          .append(failureVar).append(");\n");
        sb.append("  }\n");

        genCtx.metricDeclarations.add(
            new TALMetricDeclaration(fullName, function.meterFunction, scopeType, block.getName(), bounds, ranks,
                labelLimit));
    }

    /**
     * The observation the function accepts: a number for most, the {@code match} condition for {@code percent},
     * an argument object for {@code apdex}, and a bucketed or labeled value for the rest.
     *
     * @param entityVar the entity the metric is scoped to; {@code apdex} looks its threshold up by that entity's
     *                  service, the name as the meter system stored and the UI shows it
     */
    private static void appendObservation(final StringBuilder sb,
                                          final TALScriptModel.MetricsBlock block,
                                          final TALMetricFunction function,
                                          final String entityVar,
                                          final List<Long> bounds,
                                          final List<Integer> ranks,
                                          final TALGenCtx genCtx) {
        switch (function.kind) {
            case BOOLEAN:
                sb.append("Boolean.valueOf(");
                TALValueCodegen.generateCondition(sb, block.getMatch(), genCtx);
                sb.append(")");
                break;
            case APDEX:
                sb.append("new ").append(APDEX_ARGUMENT).append("((int) (");
                appendLong(sb, block.getValue(), block.getValueCast(), genCtx);
                sb.append("), ").append(entityVar).append(".getServiceName(), ");
                sb.append("Boolean.valueOf(");
                TALValueCodegen.generateCondition(sb, block.getStatus(), genCtx);
                sb.append(").booleanValue())");
                break;
            case PERCENTILE:
                sb.append("new ").append(PERCENTILE_ARGUMENT).append("(");
                appendBucketedValues(sb, block, bounds, genCtx);
                sb.append(", ").append(ranksArray(ranks)).append(")");
                break;
            case LABELED:
                appendLabeledValue(sb, block, genCtx);
                break;
            case LONG:
            default:
                sb.append("Long.valueOf(");
                appendLong(sb, block.getValue(), block.getValueCast(), genCtx);
                sb.append(")");
                break;
        }
    }

    /**
     * A {@code value} or {@code timestamp} as a primitive long. A numeric {@code as} cast converts first and
     * truncates after, so {@code value attr("x") as Double} takes {@code "1.7"} as 1 rather than failing to parse
     * it as a long.
     */
    private static void appendLong(final StringBuilder sb,
                                   final TALScriptModel.ValueAccess value,
                                   final String cast,
                                   final TALGenCtx genCtx) {
        TALValueCodegen.generateArgumentFor(sb, value, cast, long.class, "a metric's value or timestamp", genCtx);
    }

    /**
     * Place the observation in the first bucket whose bound is not below it. An overflow bucket keyed
     * {@code Long.MAX_VALUE} follows the declared bounds, the key MAL gives OTel's {@code +Inf} bucket, so a value
     * above the last bound is not counted as if it were at that bound.
     */
    private static void appendBucketedValues(final StringBuilder sb,
                                             final TALScriptModel.MetricsBlock block,
                                             final List<Long> bounds,
                                             final TALGenCtx genCtx) {
        // The bounds are emitted as parsed numbers, not as the rule spelled them: Javassist reads `010L` as octal.
        sb.append(TALRuntimeRoles.method("bucketed")).append("(new long[] {");
        for (int i = 0; i < bounds.size(); i++) {
            if (i > 0) {
                sb.append(", ");
            }
            sb.append(bounds.get(i)).append("L");
        }
        if (bounds.get(bounds.size() - 1) != Long.MAX_VALUE) {
            sb.append(", ").append(Long.MAX_VALUE).append("L");
        }
        sb.append("}, ");
        appendLong(sb, block.getValue(), block.getValueCast(), genCtx);
        sb.append(")");
    }

    private static String ranksArray(final List<Integer> ranks) {
        final StringBuilder out = new StringBuilder("new int[] {");
        for (int i = 0; i < ranks.size(); i++) {
            if (i > 0) {
                out.append(", ");
            }
            out.append(ranks.get(i));
        }
        return out.append("}").toString();
    }

    private static void appendLabeledValue(final StringBuilder sb,
                                           final TALScriptModel.MetricsBlock block,
                                           final TALGenCtx genCtx) {
        sb.append(TALRuntimeRoles.method("labeled")).append("(new String[] {");
        int i = 0;
        for (final Map.Entry<String, TALScriptModel.TagValue> e : block.getLabels().entrySet()) {
            if (i++ > 0) {
                sb.append(", ");
            }
            sb.append("\"").append(DslJavaSourceText.toLiteral(e.getKey())).append("\", ");
            TALValueCodegen.generateStringValueAccess(
                sb, e.getValue().getValue(), e.getValue().getCastType(), genCtx);
        }
        sb.append("}, ");
        appendLong(sb, block.getValue(), block.getValueCast(), genCtx);
        sb.append(")");
    }

    /**
     * Emit the entity a {@code scope} names: an inline constructor, or a {@code def} variable already holding
     * one.
     *
     * @return the {@code ScopeType} name the metric is registered under
     */
    private static String appendEntity(final StringBuilder sb,
                                       final TALValueAccess scope,
                                       final TALGenCtx genCtx) {
        if (scope == null) {
            throw new IllegalArgumentException("a metrics block needs a scope");
        }
        final String constructor = scope.getFunctionCallName();
        if (constructor == null) {
            final String varName = scope.getSegments().get(0);
            final String scopeType = genCtx.entityScopeTypes.get(varName);
            if (scopeType == null) {
                throw new IllegalArgumentException(
                    "scope '" + varName + "' is not an entity; assign one with an entity constructor first");
            }
            // The variable's current Java local, which a redeclaration after an ended scope names afresh.
            sb.append(genCtx.localVars.get(varName).javaVarName);
            return scopeType;
        }
        return appendEntityConstructor(sb, scope, genCtx);
    }

    /**
     * The entity constructors, recognized by name. Each maps onto a {@code MeterEntity} factory; the relation
     * ones take a layer per side, because a span's peer is conjectured while its own service is not.
     */
    static String appendEntityConstructor(final StringBuilder sb,
                                          final TALValueAccess scope,
                                          final TALGenCtx genCtx) {
        final String name = scope.getFunctionCallName();
        final List<? extends TALFunctionArg> args = scope.getFunctionCallArgs();
        switch (name) {
            case "service":
                requireArgs(name, args, 2);
                sb.append(METER_ENTITY).append(".newService(");
                str(sb, args, 0, genCtx);
                sb.append(", ");
                layer(sb, args, 1, genCtx);
                sb.append(")");
                return "SERVICE";
            case "instance":
                requireArgs(name, args, 3);
                sb.append(METER_ENTITY).append(".newServiceInstance(");
                str(sb, args, 0, genCtx);
                sb.append(", ");
                str(sb, args, 1, genCtx);
                sb.append(", ");
                layer(sb, args, 2, genCtx);
                sb.append(", null)");
                return "SERVICE_INSTANCE";
            case "endpoint":
                requireArgs(name, args, 3);
                sb.append(METER_ENTITY).append(".newEndpoint(");
                str(sb, args, 0, genCtx);
                sb.append(", ");
                str(sb, args, 1, genCtx);
                sb.append(", ");
                layer(sb, args, 2, genCtx);
                sb.append(")");
                return "ENDPOINT";
            case "serviceRelation":
                requireArgs(name, args, 6);
                sb.append(METER_ENTITY).append(".newServiceRelation(");
                str(sb, args, 1, genCtx);
                sb.append(", ");
                layer(sb, args, 2, genCtx);
                sb.append(", ");
                str(sb, args, 3, genCtx);
                sb.append(", ");
                layer(sb, args, 4, genCtx);
                sb.append(", ").append(detectPoint(args.get(0))).append(", ");
                intArg(sb, args, 5, genCtx);
                sb.append(")");
                return "SERVICE_RELATION";
            case "serviceInstanceRelation":
                requireArgs(name, args, 8);
                sb.append(METER_ENTITY).append(".newServiceInstanceRelation(");
                str(sb, args, 1, genCtx);
                sb.append(", ");
                str(sb, args, 2, genCtx);
                sb.append(", ");
                layer(sb, args, 3, genCtx);
                sb.append(", ");
                str(sb, args, 4, genCtx);
                sb.append(", ");
                str(sb, args, 5, genCtx);
                sb.append(", ");
                layer(sb, args, 6, genCtx);
                sb.append(", ").append(detectPoint(args.get(0))).append(", ");
                intArg(sb, args, 7, genCtx);
                sb.append(")");
                return "SERVICE_INSTANCE_RELATION";
            default:
                throw new IllegalArgumentException(
                    "'" + name + "' is not an entity constructor; expected one of "
                        + TALSpanRootResolver.ENTITY_CONSTRUCTORS);
        }
    }

    private static void str(final StringBuilder sb, final List<? extends TALFunctionArg> args,
                            final int index, final TALGenCtx genCtx) {
        TALValueCodegen.generateStringValueAccess(
            sb, args.get(index).getValue(), args.get(index).getCastType(), genCtx);
    }

    private static void layer(final StringBuilder sb, final List<? extends TALFunctionArg> args,
                              final int index, final TALGenCtx genCtx) {
        sb.append(TALRuntimeRoles.method("layer")).append("(");
        str(sb, args, index, genCtx);
        sb.append(")");
    }

    private static void intArg(final StringBuilder sb, final List<? extends TALFunctionArg> args,
                               final int index, final TALGenCtx genCtx) {
        TALValueCodegen.generateArgumentFor(sb, args.get(index).getValue(), args.get(index).getCastType(), int.class,
            "a relation's component argument", genCtx);
    }

    private static String detectPoint(final TALFunctionArg arg) {
        final String text = arg.getValue().getSegments().get(0);
        if (!"CLIENT".equals(text) && !"SERVER".equals(text) || arg.getCastType() != null) {
            throw new IllegalArgumentException(
                "a relation constructor's first argument is CLIENT or SERVER, got '" + text + "'");
        }
        return DETECT_POINT + "." + text;
    }

    private static void requireArgs(final String name, final List<? extends TALFunctionArg> args,
                                    final int expected) {
        if (args.size() != expected) {
            throw new IllegalArgumentException(
                name + "() takes " + expected + " arguments, got " + args.size());
        }
    }

    /**
     * Every block names a metric, a scope and a function, and each function takes exactly the clauses it needs.
     */
    private static void validate(final TALScriptModel.MetricsBlock block,
                                 final TALMetricFunction function,
                                 final String fullName) {
        if (block.getName() == null || block.getName().isEmpty()) {
            throw new IllegalArgumentException("a metrics block needs a name");
        }
        if (block.getScope() == null) {
            throw new IllegalArgumentException("metric " + fullName + " needs a scope");
        }
        final boolean wantsValue = function.kind != TALMetricFunction.Kind.BOOLEAN;
        if (wantsValue && block.getValue() == null) {
            throw new IllegalArgumentException("metric " + fullName + " needs a value");
        }
        if (!wantsValue && block.getValue() != null) {
            throw new IllegalArgumentException("metric " + fullName + " takes match, not value");
        }
        if ((function.kind == TALMetricFunction.Kind.BOOLEAN) != (block.getMatch() != null)) {
            throw new IllegalArgumentException(
                "match belongs to percent only; metric " + fullName + " uses " + function.meterFunction);
        }
        if ((function.kind == TALMetricFunction.Kind.APDEX) != (block.getStatus() != null)) {
            throw new IllegalArgumentException(
                "status belongs to apdex only; metric " + fullName + " uses " + function.meterFunction);
        }
        if ((function.kind == TALMetricFunction.Kind.LABELED) != !block.getLabels().isEmpty()) {
            throw new IllegalArgumentException(
                "labels belong to the labeled functions only; metric " + fullName
                    + " uses " + function.meterFunction);
        }
        final boolean wantsBuckets = function.kind == TALMetricFunction.Kind.PERCENTILE;
        if (wantsBuckets == block.getBuckets().isEmpty()) {
            throw new IllegalArgumentException(
                "buckets belong to percentile only; metric " + fullName
                    + " uses " + function.meterFunction);
        }
        if (!block.getRanks().isEmpty() && function.kind != TALMetricFunction.Kind.PERCENTILE) {
            throw new IllegalArgumentException("ranks belong to percentile only; metric " + fullName);
        }
    }

    /**
     * @return the bounds as numbers, checked to be whole and strictly ascending; empty for a function without them
     */
    private static List<Long> bucketBounds(final TALScriptModel.MetricsBlock block, final String fullName) {
        final List<Long> bounds = new ArrayList<>(block.getBuckets().size());
        for (final String text : block.getBuckets()) {
            final long bound = wholeNumber(text, "bucket", fullName);
            if (!bounds.isEmpty() && bound <= bounds.get(bounds.size() - 1)) {
                throw new IllegalArgumentException(
                    "metric " + fullName + " has buckets that are not ascending: " + block.getBuckets());
            }
            bounds.add(bound);
        }
        return bounds;
    }

    /**
     * @return the ranks a percentile reports, the default set when the block names none; checked to be whole,
     * within 1..100 and strictly ascending, which is the order the percentile calculation walks them in
     */
    private static List<Integer> ranks(final TALScriptModel.MetricsBlock block,
                                       final TALMetricFunction function,
                                       final String fullName) {
        if (function.kind != TALMetricFunction.Kind.PERCENTILE) {
            return List.of();
        }
        if (block.getRanks().isEmpty()) {
            return DEFAULT_RANKS;
        }
        final List<Integer> ranks = new ArrayList<>(block.getRanks().size());
        for (final String text : block.getRanks()) {
            final long rank = wholeNumber(text, "rank", fullName);
            if (rank < 1 || rank > 100) {
                throw new IllegalArgumentException(
                    "metric " + fullName + " has a rank outside 1..100: " + block.getRanks());
            }
            if (!ranks.isEmpty() && rank <= ranks.get(ranks.size() - 1)) {
                throw new IllegalArgumentException(
                    "metric " + fullName + " has ranks that are not ascending: " + block.getRanks());
            }
            ranks.add((int) rank);
        }
        return ranks;
    }

    /**
     * @return the most label sets one row of a labeled metric holds, {@link #DEFAULT_LABEL_LIMIT} unless the block
     * names one; 0 for a metric that is not labeled. A span attribute can take any number of values, so a labeled
     * metric is always capped, as OAL's {@code labelCount} is.
     */
    private static int labelLimit(final TALScriptModel.MetricsBlock block,
                                  final TALMetricFunction function,
                                  final String fullName) {
        if (function.kind != TALMetricFunction.Kind.LABELED) {
            if (block.getLabelLimit() != null) {
                throw new IllegalArgumentException("labelLimit belongs to the labeled functions only; metric "
                    + fullName + " uses " + function.meterFunction);
            }
            return 0;
        }
        if (block.getLabelLimit() == null) {
            return DEFAULT_LABEL_LIMIT;
        }
        final long limit = wholeNumber(block.getLabelLimit(), "labelLimit", fullName);
        if (limit < 1 || limit > Integer.MAX_VALUE) {
            throw new IllegalArgumentException(
                "metric " + fullName + " has a labelLimit outside 1.." + Integer.MAX_VALUE + ": " + limit);
        }
        return (int) limit;
    }

    private static long wholeNumber(final String text, final String what, final String fullName) {
        for (int i = 0; i < text.length(); i++) {
            if (text.charAt(i) < '0' || text.charAt(i) > '9') {
                throw new IllegalArgumentException(
                    "metric " + fullName + " has a " + what + " that is not a whole number: " + text);
            }
        }
        try {
            return Long.parseLong(text);
        } catch (final NumberFormatException e) {
            throw new IllegalArgumentException(
                "metric " + fullName + " has a " + what + " beyond the range of a long: " + text);
        }
    }
