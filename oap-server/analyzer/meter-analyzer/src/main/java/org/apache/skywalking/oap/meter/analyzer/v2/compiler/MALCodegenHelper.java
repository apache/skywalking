package org.apache.skywalking.oap.meter.analyzer.v2.compiler;

import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import org.apache.skywalking.oap.server.core.dsl.debug.DSLDebugCodegenSwitch;
import org.apache.skywalking.oap.server.core.dsl.DslJavaSourceText;

/**
 * Static utility methods and constants shared across MAL code generation classes.
 */
final class MALCodegenHelper {

    /** FQCN of {@code SampleFamily} — used in generated method signatures and casts. */
    static final String SF = "org.apache.skywalking.oap.meter.analyzer.v2.dsl.SampleFamily";

    private MALCodegenHelper() {
    }

    // ---- Well-known enum types used in MAL expressions ----

    /**
     * Short name of the {@code Layer} type as written in MAL expressions. Unlike the other
     * {@link #ENUM_FQCN} entries (real Java enums), {@code Layer} is a registry-backed type
     * whose custom members have no static field, so a {@code Layer.NAME} reference is lowered
     * to a runtime {@code Layer.nameOf("NAME")} lookup in code generation rather than a
     * static-field access — see {@code MALMethodChainCodegen#generateArgument}.
     */
    static final String LAYER_ENUM_TYPE = "Layer";

    static final Map<String, String> ENUM_FQCN;

    static {
        ENUM_FQCN = new HashMap<>();
        ENUM_FQCN.put("Layer", "org.apache.skywalking.oap.server.core.analysis.Layer");
        ENUM_FQCN.put("DetectPoint",
            "org.apache.skywalking.oap.server.core.source.DetectPoint");
        ENUM_FQCN.put("K8sRetagType",
            "org.apache.skywalking.oap.meter.analyzer.v2.dsl.tagOpt.K8sRetagType");
        ENUM_FQCN.put("DownsamplingType",
            "org.apache.skywalking.oap.meter.analyzer.v2.dsl.DownsamplingType");
        ENUM_FQCN.put("TimeUnit", "java.util.concurrent.TimeUnit");
    }

    static final String RUNTIME_HELPER_FQCN =
        "org.apache.skywalking.oap.meter.analyzer.v2.compiler.rt.MalRuntimeHelper";

    /** The shared equality and truth, which the generated code calls directly. */
    static final String VALUES_FQCN = "org.apache.skywalking.oap.server.core.dsl.DslValues";

    /** FQCN of the per-rule capture binding the generated rule class carries. */
    static final String GATE_HOLDER_FQCN =
        "org.apache.skywalking.oap.server.core.dsl.debug.GateHolder";

    /** FQCN of the MAL probe class generated bytecode forwards to. */
    static final String MAL_DEBUG_FQCN =
        "org.apache.skywalking.oap.meter.analyzer.v2.dsl.debug.MALDebug";

    /**
     * Emits a gate-guarded {@code MALDebug.captureStage} call site at the current position
     * in the generated {@code run()} body. The guard reads the instance field
     * {@code debug.isGateOn()} with one volatile load — {@code false} on the idle path and JIT
     * eliminates the entire {@code if} after warm-up.
     *
     * <p>MAL probes carry the verbatim DSL fragment ({@code sourceText}) as the
     * accurate locator; no {@code sourceLine} parameter — see {@code MALDebug}'s
     * Javadoc for the rationale.
     *
     * @param sb         buffer the emitted source line is appended to
     * @param ruleName   the rule's name — Java-string-escaped before emission
     * @param sourceText verbatim DSL fragment for this stage — Java-string-escaped
     * @param var        the local variable holding the {@code SampleFamily} after the stage
     */
    static void emitCaptureStage(final StringBuilder sb, final String ruleName,
                                 final String sourceText, final String var) {
        if (!DSLDebugCodegenSwitch.isInjectionEnabled()) {
            return;
        }
        sb.append("  if (this.debug.isGateOn()) ").append(MAL_DEBUG_FQCN)
          .append(".captureStage(this.debug, \"").append(DslJavaSourceText.toLiteral(ruleName))
          .append("\", \"").append(DslJavaSourceText.toLiteral(sourceText))
          .append("\", ").append(var).append(");\n");
    }

    /**
     * Emits a gate-guarded {@code MALDebug.captureInput} call site immediately after a
     * metric reference is read from the input {@code samples} map.
     */
    static void emitCaptureInput(final StringBuilder sb, final String ruleName,
                                 final String metricRef, final String var) {
        if (!DSLDebugCodegenSwitch.isInjectionEnabled()) {
            return;
        }
        sb.append("  if (this.debug.isGateOn()) ").append(MAL_DEBUG_FQCN)
          .append(".captureInput(this.debug, \"").append(DslJavaSourceText.toLiteral(ruleName))
          .append("\", \"").append(DslJavaSourceText.toLiteral(metricRef))
          .append("\", ").append(var).append(");\n");
    }

    // ---- Method classification sets ----

    /**
     * Methods on SampleFamily that take String[] (varargs).
     * Javassist doesn't support varargs syntax, so multiple string args
     * must be wrapped in {@code new String[]{}}.
     */
    static final Set<String> VARARGS_STRING_METHODS = Set.of(
        "tagEqual", "tagNotEqual", "tagMatch", "tagNotMatch"
    );

    /**
     * Methods on SampleFamily whose first argument is a primitive {@code double}.
     * Javassist cannot auto-unbox {@code Double} to {@code double}, so numeric
     * arguments to these methods must be emitted as raw double literals.
     */
    static final Set<String> PRIMITIVE_DOUBLE_METHODS = Set.of(
        "valueEqual", "valueNotEqual", "valueGreater",
        "valueGreaterEqual", "valueLess", "valueLessEqual"
    );

    // ---- Static utility methods ----

    static String opMethodName(final MALExpressionModel.ArithmeticOp op) {
        switch (op) {
            case ADD:
                return "plus";
            case SUB:
                return "minus";
            case MUL:
                return "multiply";
            case DIV:
                return "div";
            default:
                throw new IllegalArgumentException("Unknown op: " + op);
        }
    }

    static String comparisonOperator(final MALExpressionModel.CompareOp op) {
        switch (op) {
            case GT:
                return " > ";
            case LT:
                return " < ";
            case GTE:
                return " >= ";
            case LTE:
                return " <= ";
            default:
                // == and != compare through DslValues.equal, by value.
                throw new IllegalArgumentException("No Java operator for " + op);
        }
    }

    static boolean isDownsamplingType(final String name) {
        return "AVG".equals(name) || "SUM".equals(name) || "LATEST".equals(name)
            || "SUM_PER_MIN".equals(name) || "MAX".equals(name) || "MIN".equals(name);
    }

    /**
     * Extracts a constant string key from a closure expression
     * (used for bean setter naming).
     * Returns the key string if the expression is a string literal,
     * or null otherwise.
     */
    static String extractConstantKey(final MALExpressionModel.ClosureExpr expr) {
        if (expr instanceof MALExpressionModel.ClosureStringLiteral) {
            return ((MALExpressionModel.ClosureStringLiteral) expr).getValue();
        }
        return null;
    }

    /**
     * Emits the appropriate {@code Number.valueOf()} for a numeric literal.
     * Integer-valued numbers emit {@code Long.valueOf(NL)}, others emit {@code Double.valueOf(N)}.
     */
    static void emitNumberValueOf(final StringBuilder sb, final double value) {
        // A long only where the double holds the whole number exactly; a cast past 2^53 would clamp or round.
        if (value == Math.floor(value) && Math.abs(value) <= (double) (1L << 53)) {
            sb.append("Long.valueOf(").append((long) value).append("L)");
        } else {
            sb.append("Double.valueOf(").append(value).append(')');
        }
    }
}
